/**
 * The manual's generated pages (ADR 0024): keys, console commands and DALI commands, written from
 * the tables the app itself runs on, so they cannot say something the app does not do.
 * `pnpm manual:gen` writes them to `docs/manual/generated/`, and a test fails when a file there is
 * not what this makes.
 */
import {
  DALI_GROUPS,
  daliEntry,
  daliGroup,
  GENERAL_NOTE,
  help,
  TOPIC_NAMES,
} from '../console/help.ts';
import { GROUP_TITLES } from '../console/dali-help.ts';
import { legend } from '../console/keys.ts';
import { FRIENDLY } from '../console/parse.ts';
import { APP_KEYS, PICTURE_KEYS } from '../ui/shell/keys.ts';
import { RAIL } from '../ui/shell/rail.ts';

const NOTE =
  'This page is generated by `pnpm manual:gen`. Do not edit it: change the app, then run the command.';

/** A table cell: bars escaped, so a cell cannot end early. */
const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const code = (s: string): string => `\`${s}\``;

function table(head: readonly string[], rows: readonly (readonly string[])[]): string {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
  ].join('\n');
}

const front = (title: string, order: number): string =>
  `---\ntitle: ${title}\norder: ${String(order)}\n---\n\n# ${title}\n\n${NOTE}\n`;

function keysPage(): string {
  const mac = legend('mac');
  const other = legend('other');
  const editing = mac.map((row, i) => {
    const kept = other[i]?.elsewhere ?? [];
    return [row.does, row.keys.join(', '), kept.join(', ')];
  });
  return [
    front('Keys', 1),
    '## Anywhere in the app',
    '',
    table(
      ['Keys', 'Does'],
      APP_KEYS.map(([keys, does]) => [keys, does]),
    ),
    '',
    'A single Escape keeps its usual meaning: it closes a dialog, cancels a search, or releases Tab in the console. No shortcut uses Cmd, and none uses Ctrl with Alt.',
    '',
    '## Pages',
    '',
    table(
      ['Key', 'Page'],
      [...RAIL.map((r, i) => [`Alt ${String((i + 1) % 10)}`, r.label]), ['F1', 'Manual']],
    ),
    '',
    "## On the Visualiser's picture",
    '',
    table(
      ['Keys', 'Does'],
      PICTURE_KEYS.map(([keys, does]) => [keys, does]),
    ),
    '',
    '## In the console',
    '',
    'The console edits a line as a shell does. The last column lists keys that a browser keeps for itself in a normal tab on Windows and Linux. They work on a Mac, and in an app window anywhere.',
    '',
    table(['Does', 'Keys', 'Kept by the browser in a normal tab'], editing),
    '',
  ].join('\n');
}

function consolePage(): string {
  const commands = FRIENDLY.filter((c) => TOPIC_NAMES.includes(c));
  const rows = commands.map((c) => {
    const [syntax, ...rest] = help(c, 'other');
    return [code(syntax ?? c), rest.join(' ')];
  });
  const topic = (name: string): string => help(name, 'other').join(' ');
  return [
    front('Console commands', 2),
    'Every command of the console, as `help <command>` gives it. `help -k <word>` looks a word up, and `explain <line>` shows what a line would send without sending it.',
    '',
    table(['Command', 'What it does'], rows),
    '',
    '## Addresses',
    '',
    topic('addresses'),
    '',
    '## Values',
    '',
    topic('values'),
    '',
    '## Scripts',
    '',
    topic('scripts'),
    '',
    '## On hardware',
    '',
    help('hardware', 'other')
      .map((l) => (l.startsWith('  ') ? `- ${l.trim()}` : l))
      .join('\n'),
    '',
  ].join('\n');
}

function daliPage(): string {
  const out: string[] = [
    front('DALI commands', 3),
    'Every DALI command the app supports, by the name the console takes. `help <name>` prints the same in the console. What a command does is written in the words of this project from public sources, not taken from IEC 62386. The frame, the registers and what the governor does with it come from the tables the app runs on.',
    '',
    'Device type commands get ENABLE DEVICE TYPE added, and commands the standard sends twice go twice. A name shared by a general command and a device type one is the general command, and `dt6-` or `dt8-` before a name reaches the other.',
    '',
  ];
  for (const group of DALI_GROUPS) {
    const specs = daliGroup(group);
    out.push(`## ${GROUP_TITLES[group]}`, '');
    out.push(
      table(
        ['Command', 'What it does', 'Frame and registers', 'Governor'],
        specs.map((s) => {
          const e = daliEntry(s);
          const does = [
            `**${e.label}** (${e.part}).`,
            e.does,
            e.general ? `*${GENERAL_NOTE}*` : '',
            e.see === undefined ? '' : `See also: ${e.see}`,
          ];
          const frame = [
            e.frame,
            e.registers,
            `Example: ${code(e.example)} sends ${code(e.exampleFrames)}.`,
          ];
          return [
            code(e.usage),
            does.filter((x) => x !== '').join(' '),
            frame.filter((x) => x !== '').join(' '),
            e.governor,
          ];
        }),
      ),
      '',
    );
  }
  return out.join('\n');
}

/** The generated pages, by path under `docs/manual/`. */
export function generatedPages(): Record<string, string> {
  return {
    'generated/keys.md': keysPage(),
    'generated/console-commands.md': consolePage(),
    'generated/dali-commands.md': daliPage(),
  };
}
